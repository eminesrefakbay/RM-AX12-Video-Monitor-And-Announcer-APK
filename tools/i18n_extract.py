"""Lists every text the app translates: the English strings inside tr("..."), tn("..."), I18n.t("..."), I18n.n("...").
usage: python3 tools/i18n_extract.py            -> writes app/src/main/assets/i18n/source.txt  (one English text per line, escaped)
       python3 tools/i18n_extract.py --print    -> prints them
Translators: copy source.txt, add a TAB and the translation after each line, save as <code>.tsv (see assets/i18n/*.tsv)."""
import glob, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'app/src/main/java/dev/ax12/announcer')
CALL = re.compile(r'(?:\btr|\btn|\bI18n\.t|\bI18n\.n)\(\s*"((?:\\.|[^"\\])*)"|\bI18n\.tIn\([^,]+,\s*"((?:\\.|[^"\\])*)"')

def unescape(lit):
    out, i = [], 0
    while i < len(lit):
        c = lit[i]
        if c == '\\' and i + 1 < len(lit):
            d = lit[i + 1]; i += 2
            if d == 'u': out.append(chr(int(lit[i:i + 4], 16))); i += 4
            else: out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\', '$': '$', "'": "'"}.get(d, d))
        else: out.append(c); i += 1
    return ''.join(out)

def esc(s): return s.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')

def extract():
    found = {}
    for f in sorted(glob.glob(SRC + '/*.kt') + glob.glob(SRC + '/*.java')):
        if os.path.basename(f) in ('I18n.java', 'Lang.kt'): continue
        for m in CALL.finditer(open(f, encoding='utf-8').read()):
            found.setdefault(unescape(m.group(1) if m.group(1) is not None else m.group(2)), os.path.basename(f))
    return found

def check():
    assets = os.path.join(ROOT, 'app/src/main/assets/i18n')
    def load(name):
        keys = []
        for line in open(os.path.join(assets, name), encoding='utf-8'):
            line = line.rstrip('\n')
            if not line or line.startswith('#'): continue
            k = line.split('\t', 1)[0]
            keys.append(unescape_tsv(k))
        return keys
    code = set(extract())
    bad = 0
    src = set(load('source.txt')) if False else None
    src_keys = [unescape_tsv(l.rstrip('\n')) for l in open(os.path.join(assets, 'source.txt'), encoding='utf-8') if l.strip() and not l.startswith('#')]
    if set(src_keys) != code:
        bad += 1
        print('source.txt is out of date. In the code but not in source.txt:', sorted(code - set(src_keys))[:5], ' In source.txt but not in the code:', sorted(set(src_keys) - code)[:5])
        print('  run: python3 tools/i18n_extract.py')
    for lang in ('tr', 'de', 'zh'):
        keys = load(lang + '.tsv')
        if len(keys) != len(set(keys)): bad += 1; print(lang + '.tsv has duplicate lines')
        missing = code - set(keys)
        extra = set(keys) - code
        if missing: bad += 1; print(lang + '.tsv is missing', len(missing), 'texts, for example:', sorted(missing)[:3])
        if extra: bad += 1; print(lang + '.tsv has', len(extra), 'texts the app no longer uses, for example:', sorted(extra)[:3])
    print('i18n check:', 'OK, %d texts in 4 languages' % len(code) if not bad else 'FAILED')
    return bad

def unescape_tsv(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s):
            d = s[i + 1]; out.append({'n': '\n', 't': '\t'}.get(d, d)); i += 2
        else: out.append(s[i]); i += 1
    return ''.join(out)

if __name__ == '__main__':
    if '--check' in sys.argv: sys.exit(1 if check() else 0)
    found = extract()
    if '--print' in sys.argv:
        for k, f in found.items(): print(f'{f:22s} {esc(k)}')
    else:
        out = os.path.join(ROOT, 'app/src/main/assets/i18n/source.txt')
        open(out, 'w', encoding='utf-8').write('# every English text the app translates (generated by tools/i18n_extract.py)\n' + ''.join(esc(k) + '\n' for k in found))
        print(len(found), 'texts ->', os.path.normpath(out))
